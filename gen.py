def inn10(prefix9):
    w = [2,4,10,3,5,9,4,6,8]
    d = [int(c) for c in prefix9]
    return prefix9 + str(sum(a*b for a,b in zip(w,d)) % 11 % 10)

def inn12(prefix10):
    d = [int(c) for c in prefix10]
    w1 = [7,2,4,10,3,5,9,4,6,8]
    n11 = sum(a*b for a,b in zip(w1,d)) % 11 % 10
    d.append(n11)
    w2 = [3,7,2,4,10,3,5,9,4,6,8]
    n12 = sum(a*b for a,b in zip(w2,d)) % 11 % 10
    return prefix10 + str(n11) + str(n12)

def account(bik, bal5, num7, broken=False):
    """Расчётный счёт с контрольным ключом по алгоритму Банка России (веса 7,1,3)."""
    acc = list(bal5 + '810' + '0' + '0000' + num7)
    combo = bik[-3:] + ''.join(acc)
    w = [7,1,3]
    s = sum(int(c)*w[i % 3] for i, c in enumerate(combo) if i != 11)
    k = ((10 - s % 10) * 7) % 10
    if broken:
        k = (k + 3) % 10
    acc[8] = str(k)
    return ''.join(acc)

